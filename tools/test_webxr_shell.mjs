import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html = fs.readFileSync(new URL('../addons/godot_webxr_kit/web/company_webxr_shell.html', import.meta.url), 'utf8');
const start = html.indexOf('    function selectWebRenderer(');
const end = html.indexOf('    async function startGodot()', start);
assert.ok(start >= 0 && end > start);
const context = vm.createContext({});
vm.runInContext(html.slice(start, end), context);
const caps = {webgpuApi:true, webxrWebgpu:true, immersiveVr:false, immersiveAr:false};
let config = {}; let result = context.selectWebRenderer(config, caps, '');
assert.equal(result.selected, 'webgl'); assert.equal(result.webgpuCapable, false);
assert.throws(() => context.selectWebRenderer({}, caps, 'webgpu'), /cannot run WebGPU/);
config = {experimentalWebGPU:true};result = context.selectWebRenderer(config, caps, 'webgl');
assert.equal(result.selected, 'webgl'); assert.equal(config.experimentalWebGPU, false);assert.equal(result.webgpuCapable,true);
config = {experimentalWebGPU:true};result = context.selectWebRenderer(config, caps, 'webgpu');
assert.equal(config.experimentalWebGPU,true);assert.equal(result.immersiveWebgpuCapable,true);
assert.equal(context.selectWebRenderer({experimentalWebGPU:true}, {...caps,immersiveVr:true}, '').selected,'webgl');
assert.equal(context.selectWebRenderer({experimentalWebGPU:true}, caps, '').selected,'webgpu');
assert.throws(() => context.selectWebRenderer({experimentalWebGPU:true}, {...caps,webgpuApi:false}, 'webgpu'), /cannot run WebGPU/);
assert.throws(() => context.selectWebRenderer({}, caps, 'invalid'), /renderer must/);
assert.ok(!html.includes('src="runtime_metrics_overlay.js"'));
console.log('PASS: stock/fork capability, explicit renderer selection, immersive defaults, invalid requests, self-contained shell');

config = {experimentalWebGPU:true,args:['--verbose','--rendering-driver=webgpu','--rendering-method','mobile']};
context.selectWebRenderer(config,caps,'webgl');
assert.deepEqual(Array.from(config.args),['--verbose','--rendering-driver','opengl3','--rendering-method','gl_compatibility']);
config = {experimentalWebGPU:true,args:['--rendering-method','forward_plus','--rendering-driver','opengl3']};
context.selectWebRenderer(config,caps,'webgpu');
assert.deepEqual(Array.from(config.args),['--rendering-method','forward_plus','--rendering-driver','webgpu']);
console.log('PASS: explicit engine driver and rendering-method alignment');
